/**
 * ابزار محاسبه روی رنج‌های آی‌پی نسخه ۴.
 *
 * برای «ترافیک داخلی مستقیم» لازم داریم بگوییم همه‌جا از تونل برود جز
 * رنج‌های ایران. WireGuard راهی برای «همه به جز اینها» ندارد، پس باید
 * حاصل تفریق را خودمان به صورت فهرستی از رنج‌ها حساب کنیم.
 */
object Cidr {

    data class Block(val addr: Long, val prefix: Int) {
        override fun toString(): String {
            val a = (addr shr 24) and 0xFF
            val b = (addr shr 16) and 0xFF
            val c = (addr shr 8) and 0xFF
            val d = addr and 0xFF
            return "$a.$b.$c.$d/$prefix"
        }

        val size: Long get() = 1L shl (32 - prefix)
        val start: Long get() = addr
        val end: Long get() = addr + size - 1
    }

    fun parse(cidr: String): Block? {
        val parts = cidr.trim().split("/")
        if (parts.size != 2) return null
        val prefix = parts[1].toIntOrNull() ?: return null
        if (prefix !in 0..32) return null
        val octets = parts[0].split(".")
        if (octets.size != 4) return null
        var value = 0L
        for (o in octets) {
            val n = o.toIntOrNull() ?: return null
            if (n !in 0..255) return null
            value = (value shl 8) or n.toLong()
        }
        // آدرس را به مرز رنج می‌چسبانیم تا ورودی نامرتب مشکل نسازد
        val mask = if (prefix == 0) 0L else (0xFFFFFFFFL shl (32 - prefix)) and 0xFFFFFFFFL
        return Block(value and mask, prefix)
    }

    /**
     * `0.0.0.0/0` منهای رنج‌های داده‌شده را برمی‌گرداند.
     *
     * روش کار: از کل فضا شروع می‌کنیم. اگر یک رنج کاملاً داخل فهرست حذف باشد
     * دورش می‌اندازیم، اگر هیچ برخوردی نداشته باشد نگهش می‌داریم، و اگر فقط
     * بخشی‌اش برخورد داشته باشد به دو نیم می‌شکنیمش و همین کار را تکرار می‌کنیم.
     */
    fun complement(excluded: List<String>): List<String> {
        val blocks = excluded.mapNotNull { parse(it) }
        if (blocks.isEmpty()) return listOf("0.0.0.0/0")

        val out = ArrayList<String>()
        val stack = ArrayDeque<Block>()
        stack.addLast(Block(0L, 0))

        while (stack.isNotEmpty()) {
            val current = stack.removeLast()

            val fullyCovered = blocks.any { it.start <= current.start && it.end >= current.end }
            if (fullyCovered) continue

            val overlaps = blocks.any { it.start <= current.end && it.end >= current.start }
            if (!overlaps) {
                out.add(current.toString())
                continue
            }

            // برخورد جزئی: نصفش کن. در /32 دیگر نمی‌شود شکست.
            if (current.prefix >= 32) continue
            val childPrefix = current.prefix + 1
            val half = 1L shl (32 - childPrefix)
            stack.addLast(Block(current.addr + half, childPrefix))
            stack.addLast(Block(current.addr, childPrefix))
        }
        return out.sorted()
    }

